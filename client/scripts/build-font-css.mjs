// Generates client/dist/asx_editor.css, the font and boot-shell web resource.
//
// Dataverse's webresourcetype enum has no font type and .woff2 is not an allowed
// extension, so the font cannot ship as its own web resource. It is base64-embedded
// into this type-2 CSS instead. editor.html/help.html <link> it from <head>, which
// is render-blocking, so the font arrives WITH the CSS: branded first paint, no FOUT.
//
// Manrope is variable (wght 200-800), so one file covers every weight the design uses.
//
// NOTE: FONT_STACK and the five color literals below intentionally duplicate
// src/editor/ui/tokens.ts rather than importing it. This script runs as plain node
// ESM inside the `npm run build` chain, before any TypeScript is compiled, so it
// cannot import a .ts module. Keep the two in sync by eye; there are only five values.
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const FONT = join(here, "..", "node_modules", "@fontsource-variable", "manrope", "files", "manrope-latin-wght-normal.woff2");
const OUT = join(here, "..", "dist", "asx_editor.css");

const FONT_STACK = "'Manrope', 'Segoe UI', system-ui, sans-serif";

export function buildFontCss() {
  const b64 = readFileSync(FONT).toString("base64");
  return `/* Generated by scripts/build-font-css.mjs. Do not edit. */
@font-face {
  font-family: 'Manrope';
  font-style: normal;
  font-weight: 200 800;
  font-display: block;
  src: url(data:font/woff2;base64,${b64}) format('woff2-variations');
}
html, body {
  margin: 0;
  font-family: ${FONT_STACK};
  background: #f5f6fb;
  color: #1b1c33;
}
/* Boot shell: the pre-React paint. Without this, #root's "Loading…" renders
   in the browser's default serif before any bundle executes. */
#root {
  min-height: 100vh;
}
.asx-boot {
  display: flex;
  flex-direction: column;
  align-items: center;
  justify-content: center;
  gap: 14px;
  min-height: 60vh;
  font-size: 13px;
  font-weight: 500;
  color: #565b6b;
}
.asx-boot-spinner {
  width: 26px;
  height: 26px;
  border: 2.5px solid #dcd9f6;
  border-top-color: #6462e8;
  border-radius: 999px;
  animation: asx-spin .8s linear infinite;
}
@keyframes asx-spin { to { transform: rotate(360deg); } }
@media (prefers-reduced-motion: reduce) {
  .asx-boot-spinner { animation-duration: 2.4s; }
}
`;
}

// Only write when run directly, so importing this from a test has no side effect.
if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  mkdirSync(dirname(OUT), { recursive: true });
  writeFileSync(OUT, buildFontCss());
  console.log(`build-font-css: wrote ${OUT}`);
}
